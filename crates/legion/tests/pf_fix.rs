//! `legion doctor --fix pf` on a real FreeBSD host, a lab VM: from a
//! pf.conf that does not call Legion's anchors to one that does, asked
//! first, the old file kept, loaded into pf, and nothing changed when run
//! again; a file another tool writes left alone. The VM's own pf.conf is
//! put back at the end, whatever happened.

mod common;

use common::{Lab, REMOTE, Vm, text};

/// The VM's pf.conf as it was, put back however the test ends.
struct Restore<'a> {
    lab: &'a Lab,
    vm: &'a Vm,
}

impl Drop for Restore<'_> {
    fn drop(&mut self) {
        let out = self.lab.ssh(
            self.vm,
            "cp /root/pf.conf.lab-saved /etc/pf.conf && pfctl -f /etc/pf.conf \
             && rm -f /root/pf.conf.lab-saved /etc/pf.conf.legion-*",
        );
        assert!(out.status.success(), "putting pf.conf back: {}", text(&out.stderr));
    }
}

fn sh(lab: &Lab, vm: &Vm, cmd: &str) -> (bool, String) {
    let out = lab.ssh(vm, cmd);
    (out.status.success(), text(&out.stdout) + &text(&out.stderr))
}

#[test]
#[ignore = "needs root, ZFS on FreeBSD and two more nodes; see tests/common/mod.rs"]
fn doctor_puts_pf_right_asks_first_and_changes_nothing_twice() {
    let lab = Lab::from_env();
    let vm = &lab.vms[0];
    lab.install(vm);
    let (ok, said) = sh(&lab, vm, "cp /etc/pf.conf /root/pf.conf.lab-saved");
    assert!(ok, "{said}");
    let _restore = Restore { lab: &lab, vm };

    // A host's own ruleset, calling none of Legion's anchors.
    let (ok, said) = sh(
        &lab,
        vm,
        "printf '# The host'\"'\"'s rules.\\nset skip on lo0\\npass all\\n' > /etc/pf.conf && pfctl -f /etc/pf.conf",
    );
    assert!(ok, "{said}");
    let (ok, said) = sh(&lab, vm, &format!("{REMOTE} doctor"));
    assert!(!ok && said.contains("pf.anchors"), "doctor finds the anchors missing: {said}");

    // Not at a terminal and not told yes: it says what it would do, and does nothing.
    let (ok, said) = sh(&lab, vm, &format!("{REMOTE} doctor --fix pf < /dev/null"));
    assert!(!ok, "{said}");
    assert!(said.contains("+ nat-anchor \"legion/*\""), "{said}");
    assert!(said.contains("confirm with --yes"), "{said}");
    let (_, file) = sh(&lab, vm, "cat /etc/pf.conf");
    assert!(!file.contains("legion/*"), "unchanged: {file}");

    let (ok, said) = sh(&lab, vm, &format!("{REMOTE} doctor --fix pf --yes"));
    assert!(ok, "{said}");
    assert!(said.contains("To undo: cp /etc/pf.conf.legion-"), "{said}");
    let (_, file) = sh(&lab, vm, "cat /etc/pf.conf");
    for hook in ["nat-anchor \"legion/*\"", "rdr-anchor \"legion/*\"", "anchor \"legion/*\""] {
        assert!(file.contains(hook), "{hook} added: {file}");
    }
    assert!(file.contains("# The host's rules.\nset skip on lo0\n"), "the host's lines stay: {file}");
    let (_, kept) = sh(&lab, vm, "cat /etc/pf.conf.legion-*");
    assert_eq!(kept, "# The host's rules.\nset skip on lo0\npass all\n", "the old file kept");
    let (_, loaded) = sh(&lab, vm, "pfctl -sn; pfctl -sr");
    assert!(loaded.contains("rdr-anchor \"legion/*\""), "loaded into pf: {loaded}");
    let (_, at_boot) = sh(&lab, vm, "sysrc -n pf_enable");
    assert_eq!(at_boot.trim(), "YES");
    let (ok, said) = sh(&lab, vm, &format!("{REMOTE} doctor --json"));
    let found: serde_json::Value = serde_json::from_str(said.trim()).unwrap_or_default();
    let anchors = found
        .as_array()
        .and_then(|a| a.iter().find(|f| f["id"] == "pf.anchors"))
        .map(|f| f["state"].clone());
    assert_eq!(anchors, Some("met".into()), "{ok} {said}");

    // Again: nothing to change, and no second copy.
    let (ok, said) = sh(&lab, vm, &format!("{REMOTE} doctor --fix pf --yes"));
    assert!(ok, "{said}");
    assert!(said.contains("nothing to change"), "{said}");
    let (_, copies) = sh(&lab, vm, "ls /etc/pf.conf.legion-* | wc -l");
    assert_eq!(copies.trim(), "1");

    // A file Sylve writes is left as it is.
    let sylve = "# === This file is automatically generated by Sylve, don't edit! ===\npass all\n";
    let (ok, said) = sh(&lab, vm, &format!("printf '{}' > /etc/pf.conf", sylve.replace('\'', "'\"'\"'").replace('\n', "\\n")));
    assert!(ok, "{said}");
    let (ok, said) = sh(&lab, vm, &format!("{REMOTE} doctor --fix pf --yes"));
    assert!(!ok && said.contains("Sylve writes /etc/pf.conf"), "{said}");
    let (_, file) = sh(&lab, vm, "cat /etc/pf.conf");
    assert_eq!(file, sylve, "left alone");
}
